List<SurahRange> getSurahRanges(String mushaf) {
  switch (mushaf) {
    case "madani":
      return madaniSurahRanges;
    case "indopak":
    case "indopak_tajweed":
      return indopakSurahRanges;
    default:
      return indopakSurahRanges;
  }
}

String surahNameFromPage(int pageNumber, String mushaf) {
  final ranges = getSurahRanges(mushaf);

  for (final entry in ranges) {
    if (pageNumber >= entry.start && pageNumber <= entry.end) {
      return entry.name;
    }
  }
  return "Surah";
}

List<SurahRange> surahsFromLogicalPage(int logicalPage, String mushaf) {
  final ranges = getSurahRanges(mushaf);

  return ranges.where((range) {
    return logicalPage >= range.start && logicalPage <= range.end;
  }).toList();
}

int pageFromSurah(int surah, String mushaf) {
  final ranges = getSurahRanges(mushaf);
  final entry = ranges.firstWhere(
    (e) => e.surah == surah,
    orElse: () => ranges[0],
  );
  return entry.start;
}

